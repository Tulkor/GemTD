class _Bits:
    def __init__(self, d):
        self.d, self.p, self.buf, self.n = d, 0, 0, 0
    def need(self, k):
        while self.n < k:
            if self.p >= len(self.d):
                raise EOFError
            self.buf |= self.d[self.p] << self.n
            self.p += 1
            self.n += 8
    def peek(self, k):
        self.need(k)
        return self.buf & ((1 << k) - 1)
    def drop(self, k):
        self.buf >>= k
        self.n -= k
    def get(self, k):
        v = self.peek(k)
        self.drop(k)
        return v

def _mk_lookup(bits, codes):
    lut = {}
    for i, (b, c) in enumerate(zip(bits, codes)):
        lut[(b, c & ((1 << b) - 1))] = i
    return lut

_LEN_LUT = _mk_lookup(_LEN_BITS, _LEN_CODE)
_DIST_LUT = _mk_lookup(_DIST_BITS, _DIST_CODE)
_CH_LUT = _mk_lookup(_CH_BITS, _CH_CODE)

def _decode(bs, lut, maxbits):
    for b in range(1, maxbits + 1):
        try:
            v = bs.peek(b)
        except EOFError:
            bs.need(0)
            v = bs.buf & ((1 << b) - 1)
        if (b, v) in lut:
            bs.drop(b)
            return lut[(b, v)]
    raise ValueError('bad code')

def explode(data):
    ctype, dbits = data[0], data[1]
    bs = _Bits(data[2:])
    out = bytearray()
    try:
        while True:
            if bs.get(1):
                li = _decode(bs, _LEN_LUT, 7)
                length = _LEN_BASE[li] + (bs.get(_EX_BITS[li]) if _EX_BITS[li] else 0) + 2
                if length == 519:
                    break
                di = _decode(bs, _DIST_LUT, 8)
                if length == 2:
                    dist = (di << 2) | bs.get(2)
                else:
                    dist = (di << dbits) | bs.get(dbits)
                dist += 1
                for _ in range(length):
                    out.append(out[-dist])
            else:
                if ctype == 0:
                    out.append(bs.get(8))
                else:
                    out.append(_decode(bs, _CH_LUT, 13))
    except EOFError:
        pass
    return bytes(out)

def decompress(data, want):
    if len(data) >= want:
        return data[:want]
    m = data[0]
    d = data[1:]
    if m & 0x10:
        d = bz2.decompress(d)
    if m & 0x08:
        d = explode(d)
    if m & 0x02:
        d = zlib.decompress(d)
    if m & ~(0x10 | 0x08 | 0x02):
        raise ValueError('unsupported compression %x' % m)
    return d


class MPQ:
    def __init__(self, path):
        self.f = open(path, 'rb').read()
        off = 0
        while off < len(self.f):
            if self.f[off:off + 4] == b'MPQ\x1a':
                break
            off += 512
        self.base = off
        (hsz, asz, ver, sshift, htp, btp, hte, bte) = struct.unpack_from('<4xIIHHIIII', self.f, off)
        self.sector = 512 << sshift
        # geschuetzte Karten: Tabellengroessen an Dateiende begrenzen
        hte = min(hte, (len(self.f) - off - htp) // 16)
        bte = min(bte, (len(self.f) - off - btp) // 16)
        ht = decrypt(self.f[off + htp: off + htp + hte * 16], hs('(hash table)', 3))
        bt = decrypt(self.f[off + btp: off + btp + bte * 16], hs('(block table)', 3))
        self.hash = [struct.unpack_from('<IIHHI', ht, i * 16) for i in range(hte)]
        self.block = [struct.unpack_from('<IIII', bt, i * 16) for i in range(bte)]

    def find(self, name):
        a, b = hs(name, 1), hs(name, 2)
        n = len(self.hash)
        i = hs(name, 0) % n
        for _ in range(n):
            h = self.hash[i]
            if h[4] == 0xFFFFFFFF:
                return None
            if h[0] == a and h[1] == b and h[4] < len(self.block):
                return h[4]
            i = (i + 1) % n
        return None

    def read(self, name):
        bi = self.find(name)
        if bi is None:
            return None
        boff, csize, fsize, flags = self.block[bi]
        boff &= 0xFFFFFFFF
        start = self.base + boff
        raw = self.f[start:start + csize]
        key = 0
        if flags & 0x10000:
            key = hs(os.path.basename(name.replace('\\', '/')), 3)
            if flags & 0x20000:
                key = ((key + boff) ^ fsize) & 0xFFFFFFFF
        if flags & 0x1000000:  # single unit
            if flags & 0x10000:
                raw = decrypt(raw, key)
            return decompress(raw, fsize) if flags & 0x300 and csize < fsize else raw[:fsize]
        nsec = (fsize + self.sector - 1) // self.sector
        if not (flags & 0x300):
            out = bytearray()
            for s in range(nsec):
                chunk = raw[s * self.sector:(s + 1) * self.sector]
                if flags & 0x10000:
                    chunk = decrypt(chunk, (key + s) & 0xFFFFFFFF)
                out += chunk
            return bytes(out[:fsize])
        cnt = nsec + 1 + (1 if flags & 0x04000000 else 0)
        otab = raw[:cnt * 4]
        if flags & 0x10000:
            otab = decrypt(otab, (key - 1) & 0xFFFFFFFF)
        offs = struct.unpack('<%dI' % cnt, otab)
        out = bytearray()
        for s in range(nsec):
            chunk = raw[offs[s]:offs[s + 1]]
            if flags & 0x10000:
                chunk = decrypt(chunk, (key + s) & 0xFFFFFFFF)
            want = min(self.sector, fsize - s * self.sector)
            if flags & 0x100:
                out += explode(chunk) if len(chunk) < want else chunk
            else:
                out += decompress(chunk, want)
        return bytes(out[:fsize])


